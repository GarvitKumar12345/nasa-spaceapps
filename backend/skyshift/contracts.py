class Epoch(Contract):
    """An instant with an explicit time scale.

    `value`/`format`/`scale` preserve the original convention (e.g. Gaia DR3
    reference epoch 2016.0, jyear, TCB). `mjd_tdb` is derived by the backend
    with astropy for model computations; `iso_utc` is a derived display value.
    """

    value: float | str
    format: Literal["isot", "mjd", "jd", "jyear"]
    scale: TimeScale
    mjd_tdb: float = Field(description="Derived: same instant as MJD in TDB")
    iso_utc: str | None = Field(None, description="Derived display value (UTC ISO-8601)")


class SkyPosition(Contract):
    ra_deg: float = Field(ge=0.0, lt=360.0)
    dec_deg: float = Field(ge=-90.0, le=90.0)
    frame: Literal["icrs"] = "icrs"
    epoch: Epoch | None = Field(None, description="Epoch of this position, required for moving sources")


