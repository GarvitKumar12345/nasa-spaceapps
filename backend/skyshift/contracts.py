"""Normalized SkyShift data contracts.

Every scientific value that crosses the API carries:
  * its origin (observed / simulated / simulation_truth / derived_measurement /
    model_prediction / catalog),
  * units (in field names or explicit `unit` fields),
  * epochs with an explicit time scale,
  * a coordinate frame (ICRS unless stated),
  * quality and uncertainty status,
  * provenance (provider, release, method and method version).

Conventions (see CLAUDE.md):
  * Pixel coordinates in the API are 0-based with integer values at pixel
    centers; numpy index [iy, ix] <-> (x=ix, y=iy). FITS headers inside
    `WCSDescription.header` keep the FITS 1-based CRPIX convention.
  * `ra_cosdec` / `pmra` quantities are dRA * cos(Dec) (Gaia `pmra` convention).
  * Tangent-plane offsets are (east = +RA*cos(Dec), north = +Dec) in mas.
  * Astrometric model times are TDB (`Epoch.mjd_tdb`); recorded times keep
    their original scale in `Epoch.scale`.
  * NaN/inf are rejected; unavailable values are `None` with a status/reason.

Schema changes must bump CONTRACTS_VERSION and regenerate the TypeScript
types (see scripts/export_contracts.py).
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

CONTRACTS_VERSION = "skyshift.contracts/1"
EVIDENCE_SCHEMA_VERSION = "skyshift.evidence/1"
VALIDATION_SCHEMA_VERSION = "skyshift.validation/1"


class Contract(BaseModel):
    """Base for all contracts: no unknown fields, no NaN/inf."""

    model_config = ConfigDict(
        extra="forbid",
        allow_inf_nan=False,
        populate_by_name=True,
        # Serialized output always contains every field, so the exported schema marks them required.
        json_schema_serialization_defaults_required=True,
    )


# ---------------------------------------------------------------------------
# Shared vocabularies
# ---------------------------------------------------------------------------

DataOrigin = Literal[
    "observed",  # recorded by a real instrument, delivered by an archive
    "simulated",  # generated by a SkyShift simulator (pixels, simulated catalog)
    "simulation_truth",  # injected values used to generate simulated data; never a measurement
    "derived_measurement",  # computed by SkyShift from data arrays (positions, fluxes, fit estimates)
    "model_prediction",  # evaluated from a declared model + parameters
    "catalog",  # values copied from an external archive catalog (e.g. Gaia DR3)
]

ProviderId = Literal["synthetic", "spherex", "gaia_dr3", "wise", "neossat"]

IntegrationStatus = Literal[
    "documented",  # documentation reviewed; no code yet
    "implemented",  # code exists; not yet verified by a check
    "tested",  # verified by an executed check (see validation report)
    "failed",  # an executed check failed
    "unavailable",  # service unreachable / blocked when checked
    "not_run",  # check exists or is planned but has not been executed
    "not_implemented",  # planned; no code
]

QualityLevel = Literal["ok", "warning", "pending", "rejected", "unavailable"]

UncertaintyStatus = Literal[
    "estimated",  # from a fit covariance / noise model
    "propagated",  # propagated from input uncertainties through a transform
    "catalog_reported",  # copied from a catalog
    "not_available",
    "not_applicable",  # e.g. simulation truth
]

TimeScale = Literal["utc", "tai", "tt", "tdb", "tcb"]


class Quality(Contract):
    status: QualityLevel
    flags: list[str] = Field(default_factory=list, description="Machine-readable flags, e.g. MASKED_PIXELS_IN_FIT")
    messages: list[str] = Field(default_factory=list, description="Human-readable explanations")


