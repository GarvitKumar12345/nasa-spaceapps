import { expect, test } from '@playwright/test'

test.describe('[browser] BlinkIR native educational module', () => {
  test('presets, pixel selection, model context, comparison, export, and pausing on navigation', async ({ page }) => {
    await page.goto('/#/blinkir')
    await expect(page.getByTestId('bi-images').locator('canvas')).toHaveCount(2)
    await expect(page.getByTestId('blinkir-page')).toContainText('Synthetic simulation')
    await expect(page.getByTestId('bi-spectrum')).toBeVisible()
    await expect(page.getByLabel('Detector wavelength context')).toContainText('µm')
    await page.screenshot({ path:'../validation/results/blinkir-desktop.png', fullPage:true })
    await page.getByLabel('Inspect model sample').fill('70')
    await page.getByLabel('Detector wavelength context').selectOption('4')
    await page.getByLabel('Model curve', { exact: true }).selectOption('background_value')
    await page.getByTestId('bi-images').locator('canvas').first().click({ position: { x: 40, y: 40 } })
    await expect(page.getByTestId('bi-pixel')).not.toContainText('x 32, y 32')
    await page.getByRole('button', { name: 'Difference B − A', exact: true }).click()
    await expect(page.getByTestId('bi-images')).toContainText('Synthetic difference')
    await page.getByRole('button', { name: 'Blink epochs', exact: true }).click()
    await page.getByRole('button', { name: 'Play blinking', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Pause blinking' })).toBeVisible()
    const start = await page.getByLabel('Shown epoch').inputValue()
    await expect.poll(() => page.getByLabel('Shown epoch').inputValue(), { intervals: [150] }).not.toBe(start)
    await page.getByTestId('nav-methods').click()
    await page.getByTestId('nav-blinkir').click()
    await expect(page.getByRole('button', { name: 'Play blinking', exact: true })).toBeVisible()
    await page.getByRole('button', { name: /RW Aurigae/ }).click()
    await expect(page.getByRole('heading', { name: 'RW Aurigae', exact:true })).toBeVisible()
    const download = page.waitForEvent('download')
    await page.getByTestId('bi-export').click()
    expect((await download).suggestedFilename()).toBe('blinkir-simulation-lesson.json')
    await page.getByRole('button', { name: 'Check BlinkIR observed capability' }).click()
    await expect(page.getByRole('alert')).toContainText('unavailable')
    await page.setViewportSize({ width:390, height:844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path:'../validation/results/blinkir-mobile.png',fullPage:true })
  })

  test('API failures stay visible; unknown searches do not invent an observation', async ({ page }) => {
    await page.goto('/#/blinkir')
    await expect(page.getByTestId('bi-images').locator('canvas')).toHaveCount(2)
    await page.getByLabel('Search supplied presets or RA, Dec').fill('unknown target')
    await page.getByRole('button', { name:'Find',exact:true }).click()
    await expect(page.getByRole('alert')).toContainText('unavailable')
    await page.route('**/api/blinkir/simulation/*', route => route.fulfill({ status:503, contentType:'application/json',body:JSON.stringify({ detail:'Archive response unavailable in test' }) }))
    await page.getByRole('button', { name:/Epsilon Indi/ }).click()
    await expect(page.getByRole('alert').first()).toContainText('unavailable')
    await expect(page.getByTestId('bi-images')).toHaveCount(0)
    await expect(page.getByTestId('bi-export')).toBeDisabled()
  })
})
